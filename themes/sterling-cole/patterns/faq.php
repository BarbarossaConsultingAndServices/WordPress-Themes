<h1 class="wp-block-heading has-text-align-center">Asked at intake, answered here</h1>
<!-- /wp:heading -->

<!-- wp:group {"style":{"spacing":{"blockGap":"1rem"}}} -->
<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>How much will my case cost?</summary><!-- wp:paragraph -->
<p>First consultation is free. After that you get a written estimate: fixed fees for wills, uncontested divorces and contract reviews; capped hourly rates for litigation. No work starts without your signed fee agreement.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is my consultation privileged and confidential?</summary><!-- wp:paragraph -->
<p>Yes. Attorney-client privilege covers your first consultation even if you never engage us. Nothing you share leaves the room without your consent.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long will my matter take?</summary><!-- wp:paragraph -->
<p>Uncontested divorces: 2–4 months. Wills: one week. Dismissal and severance reviews: days. Contested litigation: 6–18 months depending on court load. You get a timeline in writing at intake.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What documents should I bring?</summary><!-- wp:paragraph -->
<p>Whatever you have: contracts, correspondence, court papers, IDs, corporate records. Do not wait to “complete” the file — bring it as-is and we sort it in the first meeting.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Will my case go to court?</summary><!-- wp:paragraph -->
<p>Probably not: over 90% of our files settle. But every file is prepared trial-ready, which is precisely why opponents settle on good terms.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Which courts do you appear in?</summary><!-- wp:paragraph -->
<p>All New York state and federal courts, plus mediation and arbitration panels nationwide. For other states we associate trusted local counsel and stay on your file.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you offer payment plans?</summary><!-- wp:paragraph -->
<p>For private clients in family and estate matters, yes — staged payments tied to milestones. Businesses work on retainer or fixed project fees.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you take over a case from another firm?</summary><!-- wp:paragraph -->
<p>Yes, routinely. We request the file, review deadlines first, and give you a candid second opinion before you switch. Your old firm must hand over the file promptly by rule.</p>
