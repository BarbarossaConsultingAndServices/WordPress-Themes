<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>Do I need a referral to come?</summary><!-- wp:paragraph -->
<p>No — book directly with any department. If you already have a referral letter, bring it; otherwise your GP here writes one for specialists when needed.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Which insurance do you accept?</summary><!-- wp:paragraph -->
<p>All statutory insurers plus major private plans — we bill them directly, so covered visits cost you nothing on the spot. Self-payers get a written quote before treatment.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you treat children?</summary><!-- wp:paragraph -->
<p>Yes — Dr. Nair leads family care Mon–Thu, from newborn checkups to school certificates. Children under 6 get priority same-day slots every morning.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How fast do I get lab results?</summary><!-- wp:paragraph -->
<p>Standard blood work within 24 hours via SMS and patient portal; urgent values the same day by phone. Your doctor explains every result in plain words.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What counts as an emergency?</summary><!-- wp:paragraph -->
<p>Chest pain, breathing trouble, heavy bleeding, stroke signs — call +1 (555) 019-3344 any time, day or night. For anything else, same-day slots run Mon–Fri.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I get a prescription without visiting?</summary><!-- wp:paragraph -->
<p>Repeat prescriptions via telehealth or phone — usually ready within hours at our partner pharmacy. New medication always needs one examination first.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I cancel or move an appointment?</summary><!-- wp:paragraph -->
<p>Free till 24h before — reply to your confirmation SMS or call reception. No-shows twice in a row move to phone-only booking, fairly.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you offer checkups for companies?</summary><!-- wp:paragraph -->
<p>Yes — prevention packages for teams from 5 people, on-site or in-clinic, with anonymous group reports for employers. Ask for our corporate care PDF.</p>
