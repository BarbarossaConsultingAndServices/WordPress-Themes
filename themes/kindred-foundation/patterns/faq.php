<h1 class="wp-block-heading has-text-align-center">Questions, answered honestly</h1>
<!-- /wp:heading -->

<!-- wp:group {"style":{"spacing":{"blockGap":"1rem"}}} -->
<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>How much of my donation reaches the field?</summary><!-- wp:paragraph -->
<p>92 cents of every euro fund programs directly — meals, schools, visits, clinics. 5% covers operations, 3% fundraising. Audited yearly, published every March.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Are donations tax-deductible?</summary><!-- wp:paragraph -->
<p>Yes. Kindred Foundation is a registered nonprofit; you receive an official donation receipt by email instantly, valid for your tax return.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I donate monthly or sponsor a project?</summary><!-- wp:paragraph -->
<p>Both. Monthly gifts keep the kitchen running; project sponsorships (a well, a classroom term, a clinic month) come with photo reports from the field.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I become a volunteer?</summary><!-- wp:paragraph -->
<p>Fill in the form on our volunteer page — pick a role and your availability. One afternoon of training, then you start. No experience needed, minimum age 16.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I volunteer with my company team?</summary><!-- wp:paragraph -->
<p>Absolutely — team days run monthly for groups of 5 to 30. Sorting, packing, planting or cooking: write to volunteer@kindred-foundation.example.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do you prove impact?</summary><!-- wp:paragraph -->
<p>Annual audited report, quarterly field stories with photos, and open books on request. Every project page shows raised-vs-goal figures, updated weekly.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I donate food or goods instead of money?</summary><!-- wp:paragraph -->
<p>Yes — drop-offs at Kindred House, Mon–Fri 9–17. Most needed: rice, pasta, oil, canned goods, school supplies. Call ahead for furniture or large loads.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I cancel a monthly donation?</summary><!-- wp:paragraph -->
<p>One email, no questions, no retention calls. Write to hello@kindred-foundation.example and it stops immediately — and thank you for every month you gave.</p>
<!-- /wp:paragraph --></details>
