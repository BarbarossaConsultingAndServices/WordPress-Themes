<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>What vaccinations are required?</summary><!-- wp:paragraph -->
<p>Dogs: rabies, distemper, parvovirus (+ kennel cough recommended). Cats: rabies + cat flu. Proof at first stay; our vet next door vaccinates from €35 if anything’s missing.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>My pet is anxious / old / on medication. Can they stay?</summary><!-- wp:paragraph -->
<p>Almost certainly yes — a third of our guests are seniors or rescues. Tell us everything on the booking form; medication is given exactly on schedule and logged. Truly unmanageable cases get an honest no (rare).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I visit or check the pet-cam first?</summary><!-- wp:paragraph -->
<p>Tours daily 10:00–16:00, no appointment needed. Pet-cams activate at your pet’s first boarding stay — daycare parents get photo report cards instead.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What should I pack?</summary><!-- wp:paragraph -->
<p>Food for the whole stay (portion-labeled if you like), medication with instructions, one home-smelling blanket. We provide beds, bowls, toys and endless patience — no need to pack those.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What is the cancellation policy?</summary><!-- wp:paragraph -->
<p>Boarding: free till 7 days before, then 50% of the first night. Daycare &amp; grooming: free till 24h before. No-shows get a call, not a fine, the first time.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you take unneutered males / cats in heat?</summary><!-- wp:paragraph -->
<p>Unneutered males over 8 months stay in the separate gentlemen’s wing (same price). Cats in heat board in the quiet wing with extra play sessions. Just tell us upfront.</p>
<!-- /wp:paragraph --></details>
