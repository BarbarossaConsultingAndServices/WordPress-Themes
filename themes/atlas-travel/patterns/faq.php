<!-- wp:group {"style":{"spacing":{"blockGap":"1rem"}}} -->
<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>Do I need a visa for my destination?</summary><!-- wp:paragraph -->
<p>Depends on your passport and route — we check every booking individually and send you the exact requirements plus application links. Most of our EU/US guests travel visa-free to Bali, Japan, Iceland and Morocco; Egypt and others get visa-on-arrival or a quick e-visa we walk you through.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is travel insurance required?</summary><!-- wp:paragraph -->
<p>Yes — medical + evacuation cover is required on all tours, trip cancellation strongly recommended. Any reputable insurer works; our confirmation email lists minimum coverage levels and two providers travelers like.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What is the cancellation policy?</summary><!-- wp:paragraph -->
<p>Tours: free till 30 days before, then 20% of the trip price; inside 14 days 50%. Late-deal fares are non-refundable but name-changeable once. If we cancel, you always get 100% back or a free rebooking.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How much luggage can I bring?</summary><!-- wp:paragraph -->
<p>One 20 kg bag + daypack on most tours; desert and hiking tours cap at 15 kg because of transfers. Laundry stops are built into every trip over 8 days — pack half, wash once.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do I need vaccinations or fitness prep?</summary><!-- wp:paragraph -->
<p>No mandatory jabs for most routes; Egypt and Peru follow WHO routine advice. Alps Traverse needs hill fitness (3–5h hikes); all other tours are easy-moderate with opt-out rest days. Tell us about health needs on the form — guides adapt.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Are flights included?</summary><!-- wp:paragraph -->
<p>Land services always; flights optionally. We send the best flight options after booking — or book them for you at cost. Late deals show both prices side by side.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I travel solo / vegetarian / with kids?</summary><!-- wp:paragraph -->
<p>Absolutely: a third of our guests travel solo (no forced single supplement on most dates), vegetarian and vegan meals are standard options, and kids 10+ are welcome on easy tours with family departures each summer.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Who do I call during the trip?</summary><!-- wp:paragraph -->
<p>Your guide plus our 24/7 on-trip line — printed on your voucher and saved in your phone at the welcome briefing. Real humans, median pickup under 2 minutes.</p>
