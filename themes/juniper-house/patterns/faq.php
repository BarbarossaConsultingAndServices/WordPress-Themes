<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>When can I check in and out?</summary><!-- wp:paragraph -->
<p>Check-in 15:00–21:00, check-out till 11:00 (suite till 13:00). Arriving later or earlier? Call us — the door code and key box solve most cases, and luggage can always wait in the lounge.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is breakfast really included?</summary><!-- wp:paragraph -->
<p>Yes — cooked to order, 7:30–10:30, terrace in summer, room basket (€9) if you’d rather stay in bed. No sad buffet trays, promise.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I bring my dog?</summary><!-- wp:paragraph -->
<p>Please do. €15/night including biscuit, bowl and lake towel. Dogs join breakfast on the terrace; Bruno the Labrador will inspect them at the door.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I get there without a car?</summary><!-- wp:paragraph -->
<p>Train to Seeburg station (hourly from the city), then our free shuttle — call 30 minutes ahead. Cyclists: locked bike garage with chargers for e-bikes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What is the cancellation policy?</summary><!-- wp:paragraph -->
<p>Free till 7 days before arrival, then 80% of the first night. No prepayment for standard rooms; suites pay 30% deposit. Weddings have their own (fair) terms.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is the lake swimmable? Is there wifi?</summary><!-- wp:paragraph -->
<p>Lake: yes, May–September, swim pier with ladder, water quality tested weekly. Wifi: fiber, 200 Mbps measured in every room — workation-approved.</p>
