<h1 class="wp-block-heading has-text-align-center">Questions, answered</h1>
<!-- /wp:heading -->

<!-- wp:group {"style":{"spacing":{"blockGap":"1rem"}}} -->
<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>Do I need a reservation?</summary><!-- wp:paragraph -->
<p>Weekends: strongly recommended — we’re usually full by Thursday. Weekdays: often fine spontaneously, and the six bar seats are always walk-in. When in doubt, call.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I have allergies / I’m vegetarian / vegan / celiac. Can I eat here?</summary><!-- wp:paragraph -->
<p>Almost certainly yes. A third of the menu is vegetarian, most dishes adapt to gluten-free, and the kitchen handles allergies daily — mention it when booking and remind your server. Full allergen list at the counter.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Are kids and dogs welcome?</summary><!-- wp:paragraph -->
<p>Kids: very welcome until 19:00, high chairs and small portions ready. Dogs: on the terrace anytime, inside at lunch. The cellar room fits one well-behaved regular (that’s a dog joke — he’s called Bruno).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Where do I park / how do I get there?</summary><!-- wp:paragraph -->
<p>U8 Bernauer Straße is 3 minutes on foot. Parking garage on Gartenstraße (evenings €2/hour). Bike racks directly outside — we’ll watch your e-bike battery at the bar.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I book for a big group or event?</summary><!-- wp:paragraph -->
<p>Up to 12 at the round table, up to 14 in the cellar room, up to 40 for full buyouts (weddings welcome — three this year already). Write via reservations with the date and headcount.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you do takeaway and vouchers?</summary><!-- wp:paragraph -->
<p>Takeaway Tue–Fri 17:00–21:00 (call ahead, ready in 20 minutes). Gift vouchers any amount, printable at home or wax-sealed at the counter — the sealed ones get you a free affogato story.</p>
<!-- /wp:paragraph --></details>
