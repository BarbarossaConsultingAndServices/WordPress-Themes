<details class="wp-block-details"><summary>What should I check at a viewing?</summary><!-- wp:paragraph -->
<p>Bring our 12-question checklist (see the Journal): damp corners, water pressure, noise at rush hour, HOA reserves, heating age. We hand you a torch and time — take both.</p>
