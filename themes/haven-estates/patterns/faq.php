<div class="wp-block-group"><!-- wp:details -->
<details class="wp-block-details"><summary>How do viewings work?</summary><!-- wp:paragraph -->
<p>Pick 3–5 favorites and we bundle them into one tour, usually within 48 hours. Evenings and Saturdays included. You get a cost sheet per home before we go.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What does buying really cost on top of the price?</summary><!-- wp:paragraph -->
<p>Plan roughly 10–12% extra: transfer tax, notary, land registry and our fixed buyer fee quoted upfront. Every listing shows a worked example — no surprises at signing.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How fast do I need to decide after a viewing?</summary><!-- wp:paragraph -->
<p>Good homes move in 14 days median. We never pressure same-day offers — but we do call you first when a match lands, and pre-approval letters win ties.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What is your seller fee?</summary><!-- wp:paragraph -->
<p>A fixed quote in writing after valuation — no percentage creep, no hidden marketing charges. Photography, floor plans and staging advice included.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you help with financing?</summary><!-- wp:paragraph -->
<p>Yes. We model fixed-rate vs. variable payments side by side and introduce two independent advisors. Our math killed three overpriced deals last month — happily.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I sell and buy through you at the same time?</summary><!-- wp:paragraph -->
<p>That is our specialty: bridge timelines, rent-backs and aligned notary dates so you move once, not twice. Ask about the chain-free guarantee.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

